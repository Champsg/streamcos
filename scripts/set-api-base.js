'use strict';

/**
 * Points a deployed copy of the frontend at the right backend, without editing
 * source by hand.
 *
 * Cloudflare quick tunnels get a new hostname every restart, which used to
 * require editing frontend/js/app.js and netlify.toml and redeploying. Now:
 *   - frontend/runtime-config.js holds the API base the page should use;
 *   - netlify.toml redirects are rewritten to the same host.
 * start.js calls updateConfig() automatically when it sees the tunnel URL.
 *
 * Usage:
 *   node scripts/set-api-base.js https://something.trycloudflare.com
 *   node scripts/set-api-base.js --clear
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const RUNTIME_CONFIG = path.join(ROOT, 'frontend', 'runtime-config.js');
const NETLIFY_TOML = path.join(ROOT, 'netlify.toml');

function normaliseBase(raw) {
  const value = String(raw || '').trim().replace(/\/+$/, '');
  if (!value) return '';
  let url;
  try { url = new URL(value); } catch (e) { throw new Error('Not a valid URL: ' + value); }
  if (!/^https?:$/.test(url.protocol)) throw new Error('Only http(s) URLs are supported');
  return url.origin + (url.pathname.replace(/\/+$/, '') === '/' ? '' : url.pathname.replace(/\/+$/, ''));
}

function readNetlify() {
  try { return fs.readFileSync(NETLIFY_TOML, 'utf8'); } catch (e) { return ''; }
}

function renderNetlify(base) {
  return `[build]
  publish = "frontend"

# Generated by scripts/set-api-base.js - do not hand-edit the target URLs.
# Re-run \`npm run config:url -- <backend-url>\` (or restart start.js) whenever
# the tunnel hostname changes.
[[redirects]]
  from = "/api/*"
  to = "${base}/api/:splat"
  status = 200
  force = true

[[redirects]]
  from = "/uploads/*"
  to = "${base}/uploads/:splat"
  status = 200
  force = true

[[redirects]]
  from = "/*"
  to = "/index.html"
  status = 200
`;
}

function writeRuntimeConfig(base) {
  const body = `/* Generated by scripts/set-api-base.js - safe to edit, but it may be
 * regenerated when start.js learns the tunnel URL. An empty apiBase means
 * "same origin", which is correct when this app is served by the backend. */
window.STREAMCOS_CONFIG = { apiBase: ${JSON.stringify(base)} };
`;
  fs.mkdirSync(path.dirname(RUNTIME_CONFIG), { recursive: true });
  fs.writeFileSync(RUNTIME_CONFIG, body, 'utf8');
}

function updateConfig(rawBase) {
  const base = normaliseBase(rawBase);
  writeRuntimeConfig(base);
  fs.writeFileSync(NETLIFY_TOML, renderNetlify(base || 'http://localhost:5000'), 'utf8');
  return base;
}

module.exports = { updateConfig, normaliseBase, writeRuntimeConfig, RUNTIME_CONFIG, NETLIFY_TOML };

if (require.main === module) {
  const arg = process.argv.slice(2)[0];
  if (!arg) {
    console.error('Usage: node scripts/set-api-base.js <https://backend-url> | --clear');
    process.exit(1);
  }
  try {
    const base = updateConfig(arg === '--clear' ? '' : arg);
    console.log(base
      ? 'Frontend API base set to ' + base + ' (runtime-config.js + netlify.toml updated)'
      : 'Cleared - the frontend now uses same-origin requests.');
    console.log('Redeploy the Netlify site for the redirects to take effect.');
  } catch (err) {
    console.error(err.message);
    process.exit(1);
  }
}
